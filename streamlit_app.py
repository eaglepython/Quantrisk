"""Streamlit Community Cloud entry point.

On launch this seeds the database with demo runs up to the most recent
business day (a short backfill so the dashboard opens current, with a trend),
then runs the QuantRisk dashboard. All data shown is synthetic sample data
generated by the demo pipeline, not live portfolio data.

Continuous updates: point QR_DATABASE_URL at a persistent database (e.g. a
free Postgres) as a Streamlit secret, and schedule .github/workflows/daily.yml
to add each new business day. With a persistent database this entry point also
backfills any missing days up to today whenever the app cold-starts.
"""
from __future__ import annotations

import os
import runpy
from datetime import date, timedelta
from pathlib import Path

# Default to a local SQLite database unless the host sets one explicitly.
os.environ.setdefault("QR_DATABASE_URL", "sqlite:///data/quantrisk.db")

# How many business days of demo history to ensure on startup.
BACKFILL_DAYS = int(os.environ.get("QR_DEMO_BACKFILL_DAYS", "8"))


def _latest_business_day(d: date | None = None) -> date:
    d = d or date.today()
    while d.weekday() >= 5:  # Sat/Sun -> previous Friday
        d -= timedelta(days=1)
    return d


def _recent_business_days(n: int) -> list[date]:
    out: list[date] = []
    d = _latest_business_day()
    while len(out) < n:
        if d.weekday() < 5:
            out.append(d)
        d -= timedelta(days=1)
    return sorted(out)  # oldest first


def _ensure_sqlite_dir(database_url: str) -> None:
    """A fresh clone has no data/ folder, so SQLite cannot create the file.
    Create the parent directory of the SQLite path before any DDL runs."""
    if database_url.startswith("sqlite:///"):
        raw = database_url.removeprefix("sqlite:///")
        if raw and raw != ":memory:":
            Path(raw).parent.mkdir(parents=True, exist_ok=True)


def _seed() -> None:
    from quantrisk.cli import main as cli_main
    from quantrisk.config import load_profile_settings
    from quantrisk.data import db

    settings = load_profile_settings("demo")
    _ensure_sqlite_dir(settings.database_url)
    for key in ("raw", "curated"):
        try:
            settings.path(key).mkdir(parents=True, exist_ok=True)
        except Exception:
            pass

    engine = db.make_engine(settings.database_url)
    db.init_db(engine)

    # Which business days already have a completed run? (backfill only the gaps)
    existing: set[str] = set()
    try:
        rows = db.read_sql(engine, "select distinct as_of_date from risk_run where status = 'SUCCEEDED'")
        existing = {str(v)[:10] for v in rows["as_of_date"].tolist()}
    except Exception:
        existing = set()

    for d in _recent_business_days(BACKFILL_DAYS):
        if d.isoformat() in existing:
            continue
        try:
            cli_main(["run", "--as-of", d.isoformat(), "--with-sample", "--no-report"])
        except Exception:
            # One bad day should not stop the dashboard from opening.
            pass


# A per-container marker avoids re-seeding on every Streamlit rerun, while a new
# container (cold start) re-checks and backfills up to the current day.
_MARKER = Path("data/.demo_seeded")
if not _MARKER.exists():
    _seed()
    try:
        _MARKER.parent.mkdir(parents=True, exist_ok=True)
        _MARKER.write_text(f"seeded up to {_latest_business_day().isoformat()}\n")
    except Exception:
        pass

runpy.run_path("dashboards/app.py", run_name="__main__")
